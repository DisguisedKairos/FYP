const core = require('@actions/core');
const github = require('@actions/github');
const { OpenAI } = require('openai');

async function run() {
  try {
    const githubToken = process.env.GITHUB_TOKEN;
    const openaiApiKey = process.env.OPENAI_API_KEY;

    if (!openaiApiKey) {
      throw new Error('Missing OpenAI API Key');
    }
    if (!githubToken) {
      throw new Error('Missing GITHUB_TOKEN');
    }

    const octokit = github.getOctokit(githubToken);
    const context = github.context;

    if (!context.payload.pull_request) {
      console.log('Not a pull request event. Skipping MR review.');
      return;
    }

    const { owner, repo } = context.repo;
    const pull_number = context.payload.pull_request.number;

    console.log(`Fetching changed files for PR #${pull_number}...`);
    const { data: files } = await octokit.rest.pulls.listFiles({
      owner,
      repo,
      pull_number,
    });

    // Build a combined diff string (capped per file to avoid token overflow)
    const diffSummary = files
      .filter((file) => file.patch)
      .map(
        (file) =>
          `### File: ${file.filename} (${file.status})\n\`\`\`diff\n${file.patch.slice(0, 3000)}\n\`\`\``
      )
      .join('\n\n');

    if (!diffSummary) {
      console.log('No readable code patches found in this PR.');
      return;
    }

    console.log('Analyzing PR diff with OpenAI...');
    const openai = new OpenAI({ apiKey: openaiApiKey });

    const completion = await openai.chat.completions.create({
      model: 'gpt-4o-mini',
      messages: [
        {
          role: 'system',
          content:
            'You are an automated QA & Security Merge Request Review Agent. Analyze the provided git diff and respond in clean Markdown with four sections: 1) Summary of Changes, 2) Logic & Bug Risks, 3) Security Concerns, and 4) QA Testing Recommendations. Be concise and actionable.',
        },
        {
          role: 'user',
          content: `Please review the following Pull Request diff:\n\n${diffSummary}`,
        },
      ],
      temperature: 0.2,
    });

    const reviewBody = completion.choices[0].message.content;

    await octokit.rest.issues.createComment({
      owner,
      repo,
      issue_number: pull_number,
      body: `## 🤖 Automated QA & MR Review\n\n${reviewBody}\n\n---\n*Generated by GitHub Actions MR Review Agent*`,
    });

    console.log('Successfully posted MR review comment to the Pull Request.');
  } catch (error) {
    core.setFailed(`MR Review Agent failed: ${error.message}`);
  }
}

run();